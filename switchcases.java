public class switchcases {
    public static void main(String[] args) {
        int a = -45;
        int b = 50;
         
        switch (a+b) {
            case 0:System.out.println(" sum is 100");
            break;
            case 1:System.out.println("sum is one");
            break;
            default:System.out.println("sum is not 100/not one");
            break;
        }
    }
    
}
